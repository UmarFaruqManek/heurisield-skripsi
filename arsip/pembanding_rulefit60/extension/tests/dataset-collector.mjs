import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createDatasetCollector, DATASET_KEY, datasetRow } from '../src/storage/dataset-collector.js';
const { features } = JSON.parse(await readFile(new URL('../src/rule/feature-contract-60.json', import.meta.url)));
const vector = Object.fromEntries(features.map((name, i) => [name, i]));
vector[features[0]] = null;
const analysis = { url:'https://user:REDACTED_EMAIL/account?token=REDACTED#private', verdict:'SAFE', model_result:{ready:true}, feature_vector:{vector} };
const row = datasetRow(analysis, features);
assert.equal(Object.keys(row).length,62);
assert.equal(row.url,'https://example.org/account');
assert.equal(row.label,'legitimate');
assert.equal(row[features[0]],null);
assert.equal(datasetRow({...analysis,model_result:{ready:false}},features),null);
let saved = {}, id = 0;
const storage = {get:async()=>structuredClone(saved),set:async value=>{saved=structuredClone(value);}};
const collector = createDatasetCollector(storage,features,()=>String(++id));
await collector.record(analysis);
assert.equal(saved[DATASET_KEY].records.length,1);
await collector.enable(false); await collector.record(analysis);
assert.equal(saved[DATASET_KEY].records.length,1);
await collector.enable(true);
await Promise.all(Array.from({length:30},()=>collector.record(analysis)));
assert.equal(saved[DATASET_KEY].records.length,31);
await collector.record({...analysis,verdict:'DANGEROUS'});
assert.equal(saved[DATASET_KEY].records.length,32);
assert.equal(saved[DATASET_KEY].records.at(-1).row.label,'phishing');
await collector.enable(false);await collector.record(analysis);
assert.equal(saved[DATASET_KEY].records.length,32);
saved[DATASET_KEY].writerVersion='local-capture-v1';
saved[DATASET_KEY].error='Server unavailable';
saved[DATASET_KEY].filePath='old-server-path';
const restarted=createDatasetCollector(storage,features,()=>String(++id));
await restarted.sync();
assert.equal(saved[DATASET_KEY].writerVersion,'browser-local-v1');
assert.equal(saved[DATASET_KEY].error,'');
assert.equal(saved[DATASET_KEY].filePath,undefined);
assert.equal(saved[DATASET_KEY].records.length,32);
console.log('dataset-collector: PASS (60 values, redaction, pause, concurrency, restart, migration without data loss; no server).');
